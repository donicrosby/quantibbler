//! INT8 attention device parity — change `qk-sage-attention`, tasks 2.2/2.3.
//!
//! Scenario (spec delta `specs/qk-kernels`): `Device parity for the quantized
//! path` — on a real device the INT8 tile path matches the *quantized* NumPy
//! reference ([SA] §4 scheme, `quantibbler.kernels.attention_sage`) within a
//! block-level f32 budget (`rel <= 1e-4`), AND its quality metrics against the
//! EXACT tiled face land inside that same reference's measured envelope on the
//! very same fixture cases.
//!
//! Gate pattern (same as `gpu_attention_parity.rs`, and the spec's "both gate
//! states verified"): the file compiles only under `--features gpu`, and the
//! battery runs only under `QUANTIBBLER_GPU_TESTS=1` against real hardware —
//! unset, it prints a skip notice and returns (emulation is never a
//! correctness proof for this face).
//!
//!   QUANTIBBLER_GPU_TESTS=1 \
//!   LD_LIBRARY_PATH=/opt/data/tmp/rocm-sdk/lib \
//!   HSA_OVERRIDE_GFX_VERSION=11.5.1 \
//!   cargo test -p quantibbler-kernels --features gpu --test gpu_attention_sage
//!
//! Fixtures: `tests/fixtures/attention_sage.json`, regenerated by
//! `uv run python tools/gen_attention_sage_fixtures.py`. Each record carries
//! BOTH the quantized reference output (the parity target) and the exact face
//! output plus the reference's own [SA] §4.3 metrics on that case, so the
//! envelope check compares device numbers to measured reference numbers rather
//! than to a hand-written constant.

#![cfg(feature = "gpu")]

use quantibbler_kernels::gpu::GpuContext;
use quantibbler_kernels::gpu_attention::AttentionShape;

/// Spec budget: `rel <= 1e-4` (spec delta, `Device parity for the quantized
/// path`). The device computes f32 against an f64 reference, so the comparison
/// is two-part for the same reason the exact face's is: an infinity-norm
/// relative bound, plus a per-element bound restricted to entries within
/// `BAND` of their row's maximum — below that band relative error is dominated
/// by cancellation rather than by the kernel.
const RTOL: f64 = 1e-4;
const BAND: f64 = 1e-1;
/// [SA] §4.3 fixture-battery gates the reference itself is held to.
const COS_SIM_MIN: f64 = 0.999;
const RELATIVE_L1_MAX: f64 = 0.02;
/// Slack on the envelope check: the device may not be *worse* than the
/// reference's own measured metric by more than this.
const ENVELOPE_SLACK: f64 = 1e-3;

fn gpu_gate() -> bool {
    std::env::var("QUANTIBBLER_GPU_TESTS").is_ok_and(|v| v == "1")
}

fn load_battery() -> Vec<serde_json::Value> {
    let path = std::path::Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests")
        .join("fixtures")
        .join("attention_sage.json");
    let text = std::fs::read_to_string(&path).unwrap_or_else(|e| {
        panic!(
            "sage attention fixture unreadable ({e}); regenerate with \
             `uv run python tools/gen_attention_sage_fixtures.py`"
        )
    });
    serde_json::from_str(&text).expect("sage attention fixture is not valid JSON")
}

fn f32_flat(value: &serde_json::Value, field: &str) -> Vec<f32> {
    value[field]
        .as_array()
        .unwrap_or_else(|| panic!("fixture field {field} is not an array"))
        .iter()
        .map(|x| x.as_f64().expect("fixture element is not a number") as f32)
        .collect()
}

fn f64_flat(value: &serde_json::Value, field: &str) -> Vec<f64> {
    value[field]
        .as_array()
        .unwrap_or_else(|| panic!("fixture field {field} is not an array"))
        .iter()
        .map(|x| x.as_f64().expect("fixture element is not a number"))
        .collect()
}

fn usize_field(value: &serde_json::Value, field: &str) -> usize {
    value[field]
        .as_u64()
        .unwrap_or_else(|| panic!("fixture field {field} is missing")) as usize
}

fn f64_field(value: &serde_json::Value, field: &str) -> f64 {
    value[field]
        .as_f64()
        .unwrap_or_else(|| panic!("fixture field {field} is missing"))
}

/// Two-part parity gate; see the module docstring for why it has two parts.
/// Returns the worst per-element band error so the caller can report it.
fn assert_parity(actual: &[f32], expected: &[f64], row_len: usize, label: &str) -> f64 {
    assert_eq!(
        actual.len(),
        expected.len(),
        "{label}: device returned {} values, reference has {}",
        actual.len(),
        expected.len()
    );
    let widened: Vec<f64> = actual.iter().map(|v| f64::from(*v)).collect();
    let norm = widened
        .iter()
        .chain(expected.iter())
        .fold(0.0f64, |acc, v| acc.max(v.abs()));
    assert!(
        norm.is_finite() && norm > 0.0,
        "{label}: degenerate output norm"
    );
    let max_abs = widened
        .iter()
        .zip(expected.iter())
        .fold(0.0f64, |acc, (a, b)| acc.max((a - b).abs()));
    assert!(
        max_abs <= RTOL * norm,
        "{label}: infinity-norm relative error {:.3e} exceeds {RTOL:e} (norm {norm:.3e})",
        max_abs / norm
    );

    let mut worst = 0.0f64;
    for row in 0..(expected.len() / row_len) {
        let lo = row * row_len;
        let hi = lo + row_len;
        let row_max = expected[lo..hi]
            .iter()
            .fold(0.0f64, |acc, v| acc.max(v.abs()));
        for i in lo..hi {
            if expected[i].abs() >= BAND * row_max && expected[i].abs() > 0.0 {
                worst = worst.max((widened[i] - expected[i]).abs() / expected[i].abs());
            }
        }
    }
    assert!(
        worst <= RTOL,
        "{label}: per-element relative error {worst:.3e} exceeds {RTOL:e} inside the {BAND:e} band"
    );
    worst
}

/// [SA] §4.3 metrics, verbatim from the reference tier: Cosine Sim, Relative
/// L1 and RMSE of `candidate` against `reference`.
fn metrics(reference: &[f64], candidate: &[f32]) -> (f64, f64, f64) {
    let a = reference;
    let b: Vec<f64> = candidate.iter().map(|v| f64::from(*v)).collect();
    let dot: f64 = a.iter().zip(b.iter()).map(|(x, y)| x * y).sum();
    let na: f64 = a.iter().map(|x| x * x).sum::<f64>().sqrt();
    let nb: f64 = b.iter().map(|x| x * x).sum::<f64>().sqrt();
    let cos = dot / (na * nb);
    let num: f64 = a.iter().zip(b.iter()).map(|(x, y)| (x - y).abs()).sum();
    let den: f64 = a.iter().map(|x| x.abs()).sum();
    let rel_l1 = num / den;
    let rmse = (a
        .iter()
        .zip(b.iter())
        .map(|(x, y)| (x - y) * (x - y))
        .sum::<f64>()
        / a.len() as f64)
        .sqrt();
    (cos, rel_l1, rmse)
}

#[test]
fn sage_device_parity_and_quality_over_fixture_battery() {
    if !gpu_gate() {
        println!(
            "skip: set QUANTIBBLER_GPU_TESTS=1 (plus the staged ROCm SDK env) to run the \
             INT8 attention parity battery against real hardware"
        );
        return;
    }
    let battery = load_battery();
    assert!(!battery.is_empty(), "fixture battery is empty");
    let ctx = GpuContext::init().expect("GPU init failed; see error for the validated recipe");

    let mut ran = 0usize;
    let mut worst_parity = 0.0f64;
    let mut worst_cos = 1.0f64;
    let mut worst_rel_l1 = 0.0f64;
    for record in &battery {
        let shape = &record["shape"];
        let seq = usize_field(shape, "seq");
        let val_dim = usize_field(shape, "val_dim");
        let case = AttentionShape {
            batch: usize_field(shape, "batch"),
            n_heads: usize_field(shape, "n_heads"),
            n_kv_heads: usize_field(shape, "n_kv_heads"),
            seq_q: seq,
            seq_kv: seq,
            head_dim: usize_field(shape, "head_dim"),
            val_dim,
        };
        let causal = record["causal"]
            .as_bool()
            .expect("fixture causal flag missing");
        let block_size = usize_field(record, "block_size");
        let query = f32_flat(&record["inputs"], "query");
        let key = f32_flat(&record["inputs"], "key");
        let value = f32_flat(&record["inputs"], "value");
        let quantized = f64_flat(&record["faces"]["quantized-reference"], "out");
        let exact = f64_flat(&record["faces"]["exact"], "out");
        let ref_metrics = &record["reference_metrics"];

        let out = ctx
            .attention_sage(case, &query, &key, &value, causal, block_size)
            .unwrap_or_else(|e| panic!("sage attention launch failed on {case:?}: {e}"));
        let label = format!(
            "batch={} heads={}/{}, seq={}, d={}, val={}, block={block_size}, causal={causal}",
            case.batch, case.n_heads, case.n_kv_heads, case.seq_q, case.head_dim, case.val_dim
        );

        // 1. Parity against the quantized reference, at the spec's budget.
        worst_parity = worst_parity.max(assert_parity(&out, &quantized, val_dim, &label));

        // 2. Quality vs the EXACT face, inside the reference's measured envelope.
        let (cos, rel_l1, rmse) = metrics(&exact, &out);
        let (ref_cos, ref_rel_l1) = (
            f64_field(ref_metrics, "cosine"),
            f64_field(ref_metrics, "relative_l1"),
        );
        assert!(
            cos >= COS_SIM_MIN,
            "{label}: device Cosine Sim {cos:.6e} below the {COS_SIM_MIN} fixture gate"
        );
        assert!(
            rel_l1 <= RELATIVE_L1_MAX,
            "{label}: device Relative L1 {rel_l1:.6e} above the {RELATIVE_L1_MAX} fixture gate"
        );
        assert!(
            rmse.is_finite() && rmse > 0.0,
            "{label}: device RMSE vs the exact face is not a finite positive number"
        );
        assert!(
            cos >= ref_cos - ENVELOPE_SLACK,
            "{label}: device Cosine Sim {cos:.6e} is worse than the reference's own \
             {ref_cos:.6e} by more than {ENVELOPE_SLACK:e}"
        );
        assert!(
            rel_l1 <= ref_rel_l1 + ENVELOPE_SLACK,
            "{label}: device Relative L1 {rel_l1:.6e} is worse than the reference's own \
             {ref_rel_l1:.6e} by more than {ENVELOPE_SLACK:e}"
        );
        worst_cos = worst_cos.min(cos);
        worst_rel_l1 = worst_rel_l1.max(rel_l1);
        ran += 1;
    }
    println!(
        "sage INT8 attention: {ran}/{} fixture cases ran on the device; worst parity band \
         rel {worst_parity:.3e} (budget {RTOL:e}); worst Cosine Sim {worst_cos:.8e}; \
         worst Relative L1 {worst_rel_l1:.8e}",
        battery.len()
    );
}
